@dataclass
class AspectBehaviorCardsContext:
    """Matched behavior cards for the current astro day (derived, not stored)."""

    matches: list[dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "has_behavior_cards": len(self.matches) > 0,
            "matched_pair_keys": [m["pair_key"] for m in self.matches],
            "matches": self.matches,
        }

    @classmethod
    def from_astro_day(cls, astro_day: AstroDayPayload) -> "AspectBehaviorCardsContext":
        matches: list[dict[str, Any]] = []
        seen_pairs: set[str] = set()

        for sig in astro_day.signals:
            pk = pair_key_from_signal_key(sig.key)
            if pk is None or pk not in ASPECT_BEHAVIOR_CARD_REGISTRY:
                continue
            if pk in seen_pairs:
                continue
            seen_pairs.add(pk)

            card = ASPECT_BEHAVIOR_CARD_REGISTRY[pk]
            aspect_type = parse_aspect_type_from_signal_key(sig.key)
            nuance = polarity_nuance_ru(sig.aspect_polarity, aspect_type)

            entry: dict[str, Any] = {
                "pair_key": pk,
                "signal_key": sig.key,
                "aspect_type": aspect_type,
                "aspect_polarity": sig.aspect_polarity,
                "polarity_framing_hint_ru": nuance,
                "orb": sig.orb,
                "intensity": sig.intensity,
                "signal_class": getattr(sig, "signal_class", "foreground"),
                "card": card.to_dict(),
            }
            matches.append(entry)

        return cls(matches=matches)
