# ---------------------------------------------------------------------------
# Signal key parsing (hyphen or underscore; engine uses hyphens)
# ---------------------------------------------------------------------------

_PLANETS: frozenset[str] = frozenset(
    "sun moon mercury venus mars jupiter saturn uranus neptune pluto".split()
)

# Canonical aspect tokens in signal keys (V1 uses full names)
_ASPECT_TOKENS: frozenset[str] = frozenset(
    {"conjunction", "conjunct", "sextile", "square", "trine", "opposition"}
)

_ASPECT_CANONICAL: dict[str, str] = {
    "conjunct": "conjunction",
    "conjunction": "conjunction",
    "sextile": "sextile",
    "square": "square",
    "trine": "trine",
    "opposition": "opposition",
}


def pair_key_from_planet_names(p1: str, p2: str) -> str:
    """Stable unordered pair id: ``mars_saturn`` regardless of argument order."""
    a, b = sorted((p1.lower(), p2.lower()))
    return f"{a}_{b}"


def parse_aspect_type_from_signal_key(key: str) -> str | None:
    """Return canonical aspect type from a key like ``mars-square-saturn`` or ``saturn_trine_mars``."""
    tokens = [t for t in re.split(r"[_\-\s]+", key.lower()) if t]
    for t in tokens:
        if t in _ASPECT_TOKENS:
            return _ASPECT_CANONICAL.get(t, t)
    return None


def pair_key_from_signal_key(key: str) -> str | None:
    """Return ``planet_a_planet_b`` if exactly two distinct planets are found, else None."""
    planets = extract_planets_from_signal_key(key)
    if len(planets) != 2:
        return None
    return pair_key_from_planet_names(planets[0], planets[1])


def polarity_nuance_ru(
    aspect_polarity: AspectPolarity | None,
    aspect_type: str | None,
) -> str:
    """Minimal guidance linking card content to harmonious / tense / neutral framing."""
    ap = aspect_polarity or "neutral"
    at = aspect_type or "unknown"
    if ap == "harmonious":
        return (
            f"Аспект «{at}» в данных — гармоничный: упор на то, как структура и действие "
            "могут поддерживать друг друга, без драматизации конфликта."
        )
    if ap == "tense":
        return (
            f"Аспект «{at}» — напряжённый: упор на трение импульса и ограничений, "
            "стоп-старт, раздражение на рамки; не превращай в катастрофу."
        )
    return (
        f"Аспект «{at}» — нейтральный (соединение): слияние принципов Марса и Сатурна; "
        "смотри, что усиливается — дисциплина или внутренний стопор."
    )


