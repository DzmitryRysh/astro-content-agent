    retrograde: bool
    climate: VenusSignClimate | None

    def to_dict(self) -> dict[str, Any]:
        base: dict[str, Any] = {
            "has_climate": self.has_climate,
            "sign": self.sign,
            "retrograde": self.retrograde,
        }
        if self.has_climate and self.climate is not None:
            base["climate"] = self.climate.to_dict()
        else:
            base["climate"] = None
        return base

    @classmethod
    def from_sign(cls, sign: str, *, retrograde: bool = False) -> "VenusSignClimateContext":
        """Construct directly from a known sign string — useful for tests."""
        climate = VENUS_SIGN_CLIMATE_REGISTRY.get(sign)
        return cls(
            has_climate=climate is not None,
            sign=sign,
            retrograde=retrograde,
            climate=climate,
        )

    @classmethod
    def from_astro_day(cls, astro_day: Any) -> "VenusSignClimateContext":
        """Derive Venus sign by computing ephemeris for the day stored in *astro_day*.

        Falls back gracefully to ``has_climate=False`` if pyswisseph is unavailable
        or the computation fails for any reason.
        """
        try:
            from astro_content_agent.astro.ephemeris import compute_positions  # noqa: PLC0415

            positions = compute_positions(astro_day.day)
            venus = positions.get("Venus")
            if venus is None:
                return cls(has_climate=False, sign=None, retrograde=False, climate=None)
            return cls.from_sign(venus.sign, retrograde=venus.retrograde)
        except Exception:  # noqa: BLE001
            return cls(has_climate=False, sign=None, retrograde=False, climate=None)

    @classmethod
    def no_match(cls) -> "VenusSignClimateContext":
        """Sentinel: no climate available."""
        return cls(has_climate=False, sign=None, retrograde=False, climate=None)
