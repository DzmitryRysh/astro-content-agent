"""Venus Sign Climate — collective transiting-Venus-in-sign context for Instagram content.

This layer describes the *current shared climate* around money, comfort, desire, and
value as Venus moves through each sign.  It is NOT personal/natal Venus interpretation.

``money_poles`` (optional tuple) encodes recognizable dual styles or tension pairs
for generation — collective transit tone only, not natal houses.

Usage in content generation:
- Venus Sign Climate = background money/value/comfort style for the day/week
- Aspect triggers (from AstroEngineV1) are layered on top of this climate
- CTA is organic Instagram mode: save / comment / follow / optional soft DM
- No Money Compass / natal-house mentions in this layer

Extension: add new entries to ``VENUS_SIGN_CLIMATE_REGISTRY`` keyed by English sign name.
All 12 signs are now implemented; signs not found in the registry return a no-match context.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any

# Lazy import so tests that don't need pyswisseph can still import this module
# (compute_positions is only called inside from_astro_day at runtime).


# ---------------------------------------------------------------------------
# Climate record
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class VenusSignClimate:
    """Structured collective-climate description for Venus in a given sign."""

    sign: str
    climate_title: str
    money_style: str
    comfort_style: str
    unconscious_pull: str
    likely_leak: tuple[str, ...]
    likely_strength: tuple[str, ...]
    instagram_hook_angles: tuple[str, ...]
    instagram_cta_hint: tuple[str, ...]  # organic Instagram CTA options (save / comment / follow / soft DM)
    money_poles: tuple[str, ...] = ()  # optional dual money styles / tension labels for hooks

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


